# ─── Helper functions ───
def get_pinyin(herb):
    return HERB_PINYIN.get(herb, f'Herb-{herb}')

def get_latin(herb):
    return HERB_LATIN.get(herb, '')

def translate_syndrome(s):
    if pd.isna(s) or s == '':
        return ''
    return SYNDROME_EN.get(s, s)

def translate_disease(s):
    if pd.isna(s) or s == '':
        return ''
    return DISEASE_EN.get(s, s)

def translate_season(s):
    return SEASON_EN.get(s, s) if pd.notna(s) else ''

def translate_visit(s):
    return VISIT_EN.get(s, s) if pd.notna(s) else ''

